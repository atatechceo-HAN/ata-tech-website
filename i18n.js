/**
 * 언어 변경 실행 함수
 * @param {string} lang - 'ko' | 'en' | 'zh' | 'ja'
 */
window.setLanguage = setLanguage;
function setLanguage(lang) {
    if (!i18nData[lang]) {
        lang = 'ko';
    }

    console.log('[i18n] Setting language to:', lang);

    // 1. HTML lang 속성
    document.documentElement.lang = lang;

    // 2. localStorage 저장
    try {
        localStorage.setItem('ata_language', lang);
    } catch (e) {
        console.warn('localStorage access failed:', e);
    }

    const dict = i18nData[lang];

    // 3. data-i18n 속성 텍스트 변경
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    // 4. data-i18n-placeholder 속성 변경
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] !== undefined) {
            el.placeholder = dict[key];
        }
    });

    // 5. UI 버튼 및 체크마크 업데이트
    updateLangUI(lang);

    // 6. 드롭다운 닫기
    closeDesktopLangDropdown();
    closeMobileLangDropdown();

    // 7. 모달 명함 이미지 국문/영문 자동 연동
    if (typeof switchCardLang === 'function') {
        if (lang === 'ko') {
            switchCardLang('ko');
        } else {
            switchCardLang('en');
        }
    }
}

/**
 * 언어 셀렉터 UI 라벨 및 체크마크 동기화
 */
window.updateLangUI = updateLangUI;
function updateLangUI(lang) {
    const labels = {
        ko: '🇰🇷 한국어',
        en: '🇺🇸 English',
        zh: '🇨🇳 中文',
        ja: '🇯🇵 日本語'
    };

    const shortLabels = {
        ko: 'KO',
        en: 'EN',
        zh: 'ZH',
        ja: 'JA'
    };

    // 데스크톱 라벨
    const desktopLabel = document.getElementById('current-lang-label');
    if (desktopLabel) {
        desktopLabel.textContent = labels[lang] || labels.ko;
    }

    // 모바일 헤더 라벨
    const mobileLabel = document.getElementById('mobile-current-lang-label');
    if (mobileLabel) {
        mobileLabel.textContent = shortLabels[lang] || 'KO';
    }

    // 데스크톱 체크마크 토글
    ['ko', 'en', 'zh', 'ja'].forEach(l => {
        const check = document.getElementById('lang-check-' + l);
        if (check) {
            if (l === lang) {
                check.classList.remove('hidden');
            } else {
                check.classList.add('hidden');
            }
        }

        // 모바일 슬라이드 메뉴 버튼 활성화 스타일 토글
        const mBtn = document.getElementById('m-lang-' + l);
        if (mBtn) {
            if (l === lang) {
                mBtn.className = 'py-2 rounded-lg font-bold bg-cyan-950 text-cyan-400 border border-cyan-800/60 transition-all cursor-pointer';
            } else {
                mBtn.className = 'py-2 rounded-lg font-medium text-slate-400 hover:text-white transition-all cursor-pointer';
            }
        }
    });
}

/**
 * 데스크톱 언어 드롭다운 토글
 */
window.toggleDesktopLangDropdown = toggleDesktopLangDropdown;
function toggleDesktopLangDropdown(e) {
    if (e) {
        e.stopPropagation();
        e.preventDefault();
    }
    const dropdown = document.getElementById('desktop-lang-dropdown');
    if (dropdown) {
        dropdown.classList.remove('menu-closed');
        dropdown.classList.toggle('active-dropdown');
    }
}

window.closeDesktopLangDropdown = closeDesktopLangDropdown;
function closeDesktopLangDropdown() {
    const dropdown = document.getElementById('desktop-lang-dropdown');
    if (dropdown) {
        dropdown.classList.remove('active-dropdown');
        dropdown.classList.add('menu-closed');
    }
}

/**
 * 모바일 언어 드롭다운 토글
 */
window.toggleMobileLangDropdown = toggleMobileLangDropdown;
function toggleMobileLangDropdown(e) {
    if (e) {
        e.stopPropagation();
        e.preventDefault();
    }
    const dropdown = document.getElementById('mobile-lang-dropdown');
    if (dropdown) {
        dropdown.classList.toggle('hidden');
    }
}

window.closeMobileLangDropdown = closeMobileLangDropdown;
function closeMobileLangDropdown() {
    const dropdown = document.getElementById('mobile-lang-dropdown');
    if (dropdown) {
        dropdown.classList.add('hidden');
    }
}

// 바깥 클릭 시 모든 언어 드롭다운 닫기
document.addEventListener('click', function (e) {
    const dContainer = document.getElementById('desktop-lang-container');
    if (dContainer && !dContainer.contains(e.target)) {
        closeDesktopLangDropdown();
    }
    const mBtn = document.getElementById('mobile-lang-btn');
    const mDropdown = document.getElementById('mobile-lang-dropdown');
    if (mDropdown && !mDropdown.classList.contains('hidden')) {
        if (mBtn && !mBtn.contains(e.target) && !mDropdown.contains(e.target)) {
            closeMobileLangDropdown();
        }
    }
});


// 호버 벗어났을 때 menu-closed 해제 (다시 호버 시 열리도록)
document.addEventListener('DOMContentLoaded', function() {
    const dContainer = document.getElementById('desktop-lang-container');
    if (dContainer) {
        dContainer.addEventListener('mouseleave', function() {
            const dropdown = document.getElementById('desktop-lang-dropdown');
            if (dropdown) {
                dropdown.classList.remove('menu-closed');
            }
        });
    }
});

// ESC 키 입력 시 닫기
document.addEventListener('keydown', function(e) {
    if (e.key === 'Escape') {
        closeDesktopLangDropdown();
        closeMobileLangDropdown();
    }
});

