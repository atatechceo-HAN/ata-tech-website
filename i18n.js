/**
 * 언어 변경 실행 함수
 * @param {string} lang - 'ko' | 'en' | 'cn' | 'zh' | 'ja'
 */
window.setLanguage = setLanguage;
function setLanguage(lang, byUserSelection) {
    if (byUserSelection === undefined) byUserSelection = true;

    if (lang === 'cn' && !i18nData['cn'] && i18nData['zh']) {
        i18nData['cn'] = i18nData['zh'];
    }
    if (lang === 'zh' && !i18nData['zh'] && i18nData['cn']) {
        i18nData['zh'] = i18nData['cn'];
    }

    if (!i18nData[lang]) {
        lang = 'ko';
    }

    console.log('[i18n] Language changed to:', lang);

    // 1. HTML lang 속성
    document.documentElement.lang = (lang === 'cn' || lang === 'zh') ? 'zh-CN' : lang;

    // 2. localStorage 저장
    try {
        localStorage.setItem('ata_language', lang);
    } catch (e) {
        console.warn('localStorage access failed:', e);
    }

    const dict = i18nData[lang] || i18nData.ko;

    // 3. data-i18n 속성 텍스트 변경
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict && dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    // 4. data-i18n-placeholder 속성 변경
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict && dict[key] !== undefined) {
            el.placeholder = dict[key];
        }
    });

    // 5. 상세 페이지/제품 상세정보 영역 4개국어 동적 동기화
    window.currentLanguage = lang;
    if (typeof window.renderProductDetail === 'function') {
        window.renderProductDetail(window.currentProductId || 'delivery-vehicle', lang);
    }

    // 6. 도입 상담 모달 솔루션 옵션 언어 동기화
    if (typeof window.updateConsultSolutions === 'function') {
        window.updateConsultSolutions(lang);
    }

    // 6-2. 공지사항 게시판 4개국어 실시간 동적 동기화 (목록 및 모달 실시간 재렌더링)
    if (typeof window.syncNoticeLanguage === 'function') {
        window.syncNoticeLanguage(lang);
    }

    // 7. UI 버튼 및 체크마크 업데이트
    updateLangUI(lang);

    // 8. 드롭다운 닫기 (사용자 선택 시에만 닫힘 플래그 적용)
    closeDesktopLangDropdown(byUserSelection);
    closeMobileLangDropdown();

    // 7. 모달 명함 이미지 국문/영문 자동 연동
    if (typeof switchCardLang === 'function') {
        if (lang === 'ko') {
            switchCardLang('ko');
        } else {
            switchCardLang('en');
        }
    }

    // 8. 언어 변경 커스텀 이벤트 발송
    try {
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    } catch (e) {}
}

